#!/usr/bin/env bash
# run_route3.sh -- TRACK ROUTE3, 2026-08-31.  Driver for sim/ooc_compose4_pnr.tcl.
#
# THE QUESTION: does the composed A+B+C+D ROUTE with a NON-EMPTY
# NORM_W_IMAGE?  Every composed draw before this one carried the synthetic
# ramp, so the composed BRAM figure never included the gain store.  GAIN16
# put the store in as an 11-bit codebook index (99 RAMB36, MEASURED OOC as
# cbland) plus a 1,567-entry table, at zero DSP and zero WNS cost.  The
# composed margin on paper is 253.5 + 99 = 352.5 against 372.5 in pb_core.
# Nobody has asked the router.
#
# THE MIRROR: identical to TRACK ROUTE2's accepted configuration --
# C4_PBLOCK=1 inside the card's real pb_core (CLOCKREGION_X0Y0:X6Y3), tag
# family c4lev, CB_STYLE="distributed", HEAD's extraction of the gvr block --
# plus the one changed variable: NORM_W_IMAGE is the real 266,240-line
# norm_w_9b.hex, md5 69f614a1515e1160f5dc9e8a9e72fdc3.  Same part, same
# clocks (core 5.0 ns, hbm 4.0 ns), same threads.
#
# Tree: git archive bebd952 (the landing HEAD: GAIN16 codebook c094867,
# generator option 45cd94e, floor raise 0c16b27, board catch-up bebd952).
# ooc_normadapt_top.vhd extracted from THAT tree's llama_top; compose4_top
# generated by THAT tree's generator with --norm-w-image.
#
# NO HARDWARE.  synth_design / opt_design / place_design / route_design /
# report_* only.
#
#   run_route3.sh <stage>           stages: elab, synth, impl
#
# THE COMPLETION GATE IS THE SENTINEL, NOT THE WAITER (ROUTE2's rule):
# `C4_DONE <stage> <tag>` is the last thing the Tcl prints, and Vivado can
# print full success and then die on a Tcl error afterwards.
set -u
STAGE="${1:?stage: elab synth impl}"
TAG="${TAG:-c3img}"
ROOT=/mnt/storage/route3_2026-08-31
LOG="$ROOT/log/${STAGE}_${TAG}.log"
export C4_STAGE="$STAGE" C4_TAG="$TAG"
export C4_OUT="${C4_OUT:-$ROOT/out}"
export C4_RTL="${C4_RTL:-$ROOT/tree/rtl}"
export C4_FK33RTL="${C4_FK33RTL:-$ROOT/tree/hw/fk33/rtl}"
export C4_THREADS="${C4_THREADS:-8}"
mkdir -p "$C4_OUT" "$ROOT/log"
if [ "$STAGE" = impl ]; then
  export C4_PBLOCK="${C4_PBLOCK:-1}"
  export C4_DCP="${C4_DCP:-$C4_OUT/${TAG}_synth.dcp}"
fi

# ONE VIVADO PER BOX.  Gate on PRESENCE via /proc/PID/exe, never on a count.
for p in $(ls /proc | grep -E '^[0-9]+$'); do
  e=$(readlink "/proc/$p/exe" 2>/dev/null) || continue
  case "$e" in *unwrapped/lnx64.o/vivado*)
    echo "ROUTE3 ABORT: a Vivado is already running (pid $p)."; exit 3;; esac
done

source /tools/Xilinx/2023.2/Vivado/2023.2/settings64.sh
cd "$ROOT/tree"
vivado -mode batch -nojournal -notrace \
       -log "$ROOT/log/vivado_${STAGE}_${TAG}.log" \
       -source "$ROOT/tree/sim/ooc_compose4_pnr.tcl" >"$LOG" 2>&1
RC=$?
echo "ROUTE3 vivado_rc=$RC"
if ! grep -q "^C4_DONE $STAGE $TAG\$" "$LOG"; then
  echo "ROUTE3 FAIL: sentinel 'C4_DONE $STAGE $TAG' absent from $LOG"; exit 4
fi
echo "ROUTE3 SENTINEL OK"
exit $RC
