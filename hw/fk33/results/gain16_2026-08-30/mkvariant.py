#!/usr/bin/env python3
"""mkvariant.py -- TRACK GAIN16, 2026-08-30.

Mechanically rewrite `rtl/llama_top.vhd`'s norm-gain ROM (`gwl` block, inside
the `gvr` generate) into one of a family of STORAGE SHAPES, so that a sweep of
those shapes differs from the shipping file by exactly the edit under test and
by nothing else.  Same discipline as TRACK GWTWO's one-line `gw_pick` rewrite:
the point of a mechanical rewriter is that the control is the SHIPPING FILE and
not a re-implementation of it.

THE SHAPE FAMILY.  A shape is a list of SLICE WIDTHS, low bits first.  The
stored word is the concatenation of the slices, each slice held in its own
array with `rom_style = "block"`:

    [16]        the shipping store, one 16-bit array          (control)
    [14]        one 14-bit array                              (exact: the
                image's OR over all values is 0x3FFF, so bits 15..14 are
                always zero and dropping them is lossless FOR THIS IMAGE)
    [11], [9]   AREA PROBES.  They are LOSSY -- 1,567 distinct values need 11
                bits and the value itself needs 14 -- and exist only to
                measure the tiles-vs-width curve.  NEVER SHIP ONE.
    [9,4,1]     14 bits split three ways, each width sitting on a different
                native RAMB36 aspect ratio.

WHY THE VALUE IS TILED AND NOT ZERO-EXTENDED.  A probe that zero-extends a
9-bit store to the unit's 16-bit bank port leaves seven bits of `nw_wd`
CONSTANT ZERO, and a constant driving a memory write port is exactly the kind
of thing Vivado narrows -- which would move the unit's own RAMB18 count and
confound the very column being measured.  Tiling the stored word to 16 bits
keeps every bit of the port live.  At the 16-bit control the tiling is the
identity, so the control text is a genuine one-parameter member of the family.

NO HARDWARE.  This script reads and writes text files and nothing else.

usage: mkvariant.py <in llama_top.vhd> <out llama_top.vhd> <w0[,w1,...]>
"""

import sys

# ---------------------------------------------------------------------------
# The four anchors.  Each must match EXACTLY ONCE or the script aborts: a
# rewriter that silently matches zero times produces the control under the
# variant's name, which is the worst possible failure mode for a sweep.
# ---------------------------------------------------------------------------

A_WW = """        constant WW    : positive := GW * MANT_W;
"""

A_ROM = """        type nwrom_t is array (0 to NW_N*NWORD-1)
          of std_logic_vector(WW-1 downto 0);
"""

A_FLAT_END = """        function nwrom_flat return nwrom_t is
          variable r : nwrom_t;
        begin
          for k in 0 to NW_N-1 loop
            for w in 0 to NWORD-1 loop
              r(k*NWORD + w) := NW_TBL(k)((w+1)*WW-1 downto w*WW);
            end loop;
          end loop;
          return r;
        end function;

        signal nwrom : nwrom_t := nwrom_flat;
        attribute rom_style : string;
        attribute rom_style of nwrom : signal is "block";
"""

A_WRD = """        signal wrd   : std_logic_vector(WW-1 downto 0) := (others => '0');
"""

A_READ = """            wrd   <= nwrom(nidx*NWORD + (wel / GW));
"""

A_SUBSEL = """        wsubsel : process(wrd, wel_d) is
        begin
          nw_wd <= wrd(MANT_W-1 downto 0);
          for s in 0 to GW-1 loop
            if (wel_d mod GW) = s then
              nw_wd <= wrd((s+1)*MANT_W-1 downto s*MANT_W);
            end if;
          end loop;
        end process;
"""


def replace_once(text, anchor, new, name):
    n = text.count(anchor)
    if n != 1:
        sys.stderr.write("MKVARIANT ABORT: anchor %s matched %d times, expected 1\n"
                         % (name, n))
        sys.exit(2)
    return text.replace(anchor, new)


def build(slices):
    ns = len(slices)
    sw = sum(slices)
    offs = []
    o = 0
    for w in slices:
        offs.append(o)
        o += w

    ww = """        -- TRACK GAIN16 VARIANT, generated by
        -- hw/fk33/results/gain16_2026-08-30/mkvariant.py.  Slice widths,
        -- low bits first: %s.  Stored word width SW = %d.
        constant SW    : positive := %d;
        constant WW    : positive := SW;
""" % (",".join(str(x) for x in slices), sw, sw)

    rom = []
    for i, w in enumerate(slices):
        rom.append("""        type nwrom%d_t is array (0 to NW_N*NWORD-1)
          of std_logic_vector(%d downto 0);
""" % (i, w - 1))
    rom = "".join(rom)

    flat = []
    for i, w in enumerate(slices):
        flat.append("""        function nwrom_flat%d return nwrom%d_t is
          variable r : nwrom%d_t;
        begin
          for k in 0 to NW_N-1 loop
            for w in 0 to NWORD-1 loop
              r(k*NWORD + w) := NW_TBL(k)(w*MANT_W + %d downto w*MANT_W + %d);
            end loop;
          end loop;
          return r;
        end function;

""" % (i, i, i, offs[i] + w - 1, offs[i]))
    flat.append("        attribute rom_style : string;\n")
    for i in range(ns):
        flat.append("        signal nwrom%d : nwrom%d_t := nwrom_flat%d;\n" % (i, i, i))
        flat.append('        attribute rom_style of nwrom%d : signal is "block";\n' % i)
    flat = "".join(flat)

    wrd = "".join(
        "        signal wrd%d  : std_logic_vector(%d downto 0) := (others => '0');\n"
        % (i, w - 1) for i, w in enumerate(slices))
    wrd += "        signal wrd   : std_logic_vector(WW-1 downto 0);\n"

    read = "".join(
        "            wrd%d  <= nwrom%d(nidx*NWORD + (wel / GW));\n" % (i, i)
        for i in range(ns))

    cat = " & ".join("wrd%d" % i for i in reversed(range(ns)))
    sens = ", ".join("wrd%d" % i for i in range(ns))
    # tile the stored word up to MANT_W bits so no port bit is constant
    reps = (16 + sw - 1) // sw + 1
    subsel = """        wrd <= %s;

        -- The stored word tiled up to the bank port's MANT_W bits.  At the
        -- 16-bit control this is the identity.  See this file's header for
        -- why a probe tiles rather than zero-extends.
        wsubsel : process(%s) is
          variable t : std_logic_vector(%d*SW-1 downto 0);
        begin
          t := %s;
          nw_wd <= t(MANT_W-1 downto 0);
        end process;
""" % (cat, sens, reps, " & ".join(["wrd"] * reps))
    return ww, rom, flat, wrd, read, subsel



# ---------------------------------------------------------------------------
# THE CODEBOOK SHAPE.  `cb` replaces the 16-bit value store with an IXW-bit
# INDEX store plus a codebook, both built AT ELABORATION out of NORM_W_IMAGE
# itself.  There is deliberately no second image file, no second generic and
# no offline encoder: an offline encoder and an in-design decoder are two
# implementations that can drift, and the drift is invisible because
# decode(encode(x)) == x holds for a wrong-but-consistent pair (the `m7
# mutant` case recorded in CLAUDE.md).  Here the ONLY input is the same hex
# file the shipping design already reads.
#
# THE CODEBOOK IS READ COMBINATIONALLY, ON PURPOSE.  A registered second
# lookup would make the gain load NN+3 cycles against a budget of NN+4 where
# it is NN+2 today, and TRACK RMSWIRE's whole load-race analysis is written
# against NN+2.  Reading a distributed ROM off the index ROM's registered
# output keeps the load latency BYTE-IDENTICAL and pays for it in LUTs, which
# is the right currency: ROUTE2 measured the routed composition DSP-bound at
# 80.63% with LUT at 68.33%, and BRAM is the resource that does not fit.
# ---------------------------------------------------------------------------

CB_WW = """        -- TRACK GAIN16 CODEBOOK VARIANT, generated by
        -- hw/fk33/results/gain16_2026-08-30/mkvariant.py.
        constant WW    : positive := MANT_W;
"""

CB_ROM = """        -- The value -> index map and the index -> value table.  Both are
        -- ELABORATION-TIME only; neither becomes hardware.  The domain is the
        -- full 2**MANT_W and NOT a 14-bit window, so an image that used the
        -- top two bits would still build (more expensively) rather than break.
        type cbmap_t is array (0 to 2**MANT_W-1) of integer range -1 to 2**MANT_W-1;
        type cbtbl_t is array (0 to 2**MANT_W-1) of std_logic_vector(MANT_W-1 downto 0);
        type cbb_t is record
          n : natural;
          m : cbmap_t;
          t : cbtbl_t;
        end record;
"""

CB_FLAT = """        -- EVERY LOOP OVER 2**MANT_W IS NESTED.  Vivado's elaboration loop
        -- limit is 65,536 iterations PER LOOP STATEMENT (MEASURED, TRACK
        -- NWFIX) and 2**MANT_W is exactly 65,536, i.e. exactly at the limit.
        -- The same restructuring `nw_count` already carries, for the same
        -- reason.
        function cb_build return cbb_t is
          variable r : cbb_t;
          variable v : natural;
        begin
          for a in 0 to 255 loop
            for b in 0 to 255 loop
              r.m(a*256 + b) := -1;
            end loop;
          end loop;
          for k in 0 to NW_N-1 loop
            for i in 0 to NN-1 loop
              v := to_integer(unsigned(NW_TBL(k)((i+1)*MANT_W-1 downto i*MANT_W)));
              r.m(v) := 0;
            end loop;
          end loop;
          r.n := 0;
          for a in 0 to 255 loop
            for b in 0 to 255 loop
              if r.m(a*256 + b) = 0 then
                r.m(a*256 + b) := r.n;
                r.t(r.n) := std_logic_vector(to_unsigned(a*256 + b, MANT_W));
                r.n := r.n + 1;
              end if;
            end loop;
          end loop;
          return r;
        end function;
        constant CBB : cbb_t    := cb_build;
        constant NCB : positive := CBB.n;

        function ixw_of(n : positive) return positive is
          variable r : natural := log2c(n);
        begin
          if r = 0 then return 1; else return r; end if;
        end function;
        constant IXW : positive := ixw_of(NCB);

        type cbrom_t is array (0 to NCB-1) of std_logic_vector(MANT_W-1 downto 0);
        function cb_rom return cbrom_t is
          variable r : cbrom_t;
        begin
          for i in 0 to NCB-1 loop
            r(i) := CBB.t(i);
          end loop;
          return r;
        end function;

        type ixrom_t is array (0 to NW_N*NWORD-1)
          of std_logic_vector(IXW-1 downto 0);
        function ixrom_flat return ixrom_t is
          variable r : ixrom_t;
        begin
          for k in 0 to NW_N-1 loop
            for w in 0 to NWORD-1 loop
              r(k*NWORD + w) := std_logic_vector(to_unsigned(
                CBB.m(to_integer(unsigned(
                  NW_TBL(k)((w+1)*MANT_W-1 downto w*MANT_W)))), IXW));
            end loop;
          end loop;
          return r;
        end function;

        attribute rom_style : string;
        signal ixrom : ixrom_t := ixrom_flat;
        attribute rom_style of ixrom : signal is "block";
        signal cbrom : cbrom_t := cb_rom;
        attribute rom_style of cbrom : signal is "%(CBSTYLE)s";
"""

CB_WRD = """        signal wix   : std_logic_vector(IXW-1 downto 0) := (others => '0');
"""

CB_READ = """            wix   <= ixrom(nidx*NWORD + (wel / GW));
"""

CB_SUBSEL = """        -- The codebook lookup.  Combinational off the index ROM's REGISTERED
        -- output, so (wdv, wel_d, nw_wd) stay the matched triple they are
        -- today and the load is still NN+2 cycles.
        wsubsel : process(wix) is
        begin
          nw_wd <= cbrom(to_integer(unsigned(wix)));
        end process;
"""


def build_cb(style):
    return (CB_WW, CB_ROM, CB_FLAT % {"CBSTYLE": style}, CB_WRD, CB_READ,
            CB_SUBSEL)


def main():
    if len(sys.argv) != 4:
        sys.stderr.write(__doc__)
        return 2
    src, dst, spec = sys.argv[1], sys.argv[2], sys.argv[3]
    with open(src) as f:
        t = f.read()

    if spec.startswith("cb"):
        style = {"cb": "distributed", "cbb": "block"}.get(spec)
        if style is None:
            sys.stderr.write("MKVARIANT ABORT: bad codebook spec %r\n" % spec)
            return 2
        ww, rom, flat, wrd, read, subsel = build_cb(style)
    else:
        slices = [int(x) for x in spec.split(",")]
        if any(w < 1 for w in slices) or sum(slices) > 16:
            sys.stderr.write("MKVARIANT ABORT: bad slice spec %r\n" % spec)
            return 2
        ww, rom, flat, wrd, read, subsel = build(slices)
    t = replace_once(t, A_WW, ww, "WW")
    t = replace_once(t, A_ROM, rom, "ROM_TYPE")
    t = replace_once(t, A_FLAT_END, flat, "FLAT")
    t = replace_once(t, A_WRD, wrd, "WRD")
    t = replace_once(t, A_READ, read, "READ")
    t = replace_once(t, A_SUBSEL, subsel, "SUBSEL")

    with open(dst, "w") as f:
        f.write(t)
    sys.stderr.write("MKVARIANT OK spec=%s -> %s\n" % (spec, dst))
    return 0


if __name__ == "__main__":
    sys.exit(main())
