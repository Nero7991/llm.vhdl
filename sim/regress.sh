                         'unresolved design unit(s): %s -- nothing in rtl/, sim/, '
                         'sim/micro/ or tb/ defines them' % ', '.join(sorted(missing)),
                         '', '', ''))
            continue

        ordered, stuck = toposort(cl, tb)
        if ordered is None:
            rows.append((name, suite, 'SKIP',
                         'dependency cycle among: %s' % ', '.join(sorted(stuck)),
                         '', '', ''))
