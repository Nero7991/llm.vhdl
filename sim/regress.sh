  failed_list=()
  # Per-suite tallies, so a failure in the older generation is never hidden
  # inside a headline number dominated by the current one.
  declare -A sp sf st se sv sn
  for q in $SUITES; do sp[$q]=0; sf[$q]=0; st[$q]=0; se[$q]=0; sv[$q]=0; sn[$q]=0; done
  echo
  for q in $SUITES; do
    printf -- '-- suite %s ---------------------------------------------------------------\n' "$q"
    for e in "${selected[@]}"; do
      k="${e%%$'\t'*}"
      [ "${k%%:*}" = "$q" ] || continue
