# Generator arguments for vector files that are not committed.  Lifted from
# the mutate_*.sh / run_*.sh that owns each one, and chosen to match the
# testbench's own generic defaults -- the vector file carries a shape header
# that the testbench asserts against, so a mismatch is loud, not silent.
# A vector with no row here falls back to the generator's own defaults.
tb_vector_args() {   # <vector-file-name> -> generator argv after the filename
  case "$1" in
    # ref/attn_block_vec.c, subsystem C's BLOCK-level oracle.  The argument
    # order is HEAD_DIM N_QH N_KVH KV_BLOCK N_ROT cur_pos ctx_len seed and it
    # must match sim/tb_attn_block.vhd's generic defaults; the vector file
    # carries a shape header the bench asserts against them, so a mismatch here
    # is loud rather than a wrong answer.  N_KVH stays 2 because
    # ref/attn_block_vec.c refuses fewer, NOT because attn_emit cannot take it:
    # OI-2, the bound violation at rtl/attn_emit.vhd:400 that made NGRP = 1
    # abort, is FIXED, and sim/tb_attn_emit.vhd now runs a second instance at
    # NGRP = 1 on every gate run.
    attn_block_vec.txt)     echo "16 4 2 4 8 3 4 0" ;;
    # ref/attn_kv_axi_vec.c, the KV-cache-in-HBM oracle for rtl/attn_kv_axi.vhd.
    # Argument order is HEAD_DIM KV_BLOCK N_KVH LAYERS MAXCTX LAYER CUR_POS SEED
    # and it must match sim/tb_attn_kv_axi.vhd's generic defaults; the vector
    # file carries a shape header the harness asserts against them, so a
    # mismatch here is loud rather than a wrong answer.  HEAD_DIM 256 /
    # KV_BLOCK 32 is the BUILD geometry and is not reduced for the bench: the
    # 272-byte record is what makes REC_B indivisible by the 32-byte beat, and
    # that indivisibility is the 16-byte record phase the unit exists to handle.
    attn_kv_axi_vec.txt)    echo "256 32 2 2 32 1 20 20260828" ;;
    # ref/attn_block_seq_vec.c, the MULTI-TOKEN oracle for the attn_block <->
    # attn_kv_axi seam.  Argument order is HEAD_DIM N_QH N_KVH KV_BLOCK N_ROT
    # NTOK SEED and it must match sim/tb_attn_kv_seam.vhd's generic defaults;
    # the vector file carries a shape header the bench asserts against them.
    # KV_BLOCK 16 is the SMALLEST legal value: rtl/attn_kv_axi.vhd's record is
    # a byte layout on a 16-byte granule, so KV_BLOCK*CM_W/8 must be a
    # multiple of 16, and HEAD_DIM 64 then gives REC_B = 80, which is not a
    # multiple of the 32-byte beat -- which is the whole point, because the
    # 16-byte record phase is what the realignment mux exists for.
