    *)       rv=FAIL ;;
  esac
  [ -n "$rd" ] || rd="gray_check.sh exited $rc without a verdict line; log: $log"
  printf '%s\t%s\t%s\t%s\n' "$key" "$rv" "$(( $(date +%s) - t0 ))" "$rd" \
      > "$SCRATCH/res.${suite}_${tb}"
}

