#!/usr/bin/env bash
# sim/regress.sh -- ONE verdict for every testbench in the repo, both suites.
#
# WHY THIS EXISTS.  65 testbenches in sim/, 27 more in tb/, 80 files in rtl/,
# and about twenty
# ad-hoc run_*.sh / mutate_*.sh scripts, each of which knows how to build one
# unit.  Nothing ran them all, so verification was whatever anyone happened to
# remember, and shared units -- gdn_conv, rmsnorm_bf and gdn_emit_chain are
# each consumed by several subsystems -- were changed by one workstream and
# spot-checked by another.  That is the shape of a cross-subsystem regression
# that escapes.  This script runs everything, always, and returns non-zero if
# anything is not demonstrably green.
#
#   bash sim/regress.sh                 # full run, BOTH suites
#   bash sim/regress.sh --suite sim     # the current generation only
#   bash sim/regress.sh --suite tb      # the older tb/ set only
#   bash sim/regress.sh --quick         # pre-commit subset, 45 s at --jobs 2
#   bash sim/regress.sh --jobs 4        # more parallelism (default 2)
#   bash sim/regress.sh --only gdn      # only testbenches matching a pattern
#   bash sim/regress.sh --list          # print the plan, run nothing
#   bash sim/regress.sh --coverage      # only the RTL-without-a-testbench report
#   bash sim/regress.sh --keep          # keep the scratch tree for post-mortem
#
# ---------------------------------------------------------------------------
# TWO SUITES, KEPT SEPARATE
# ---------------------------------------------------------------------------
# sim/tb_*.vhd is the current generation.  tb/tb_*.vhd is an older set that
# sim/Makefile drives and that nothing else ran; between them they are the only
# thing reaching fifteen rtl/ files including engine, engine_shared, layer,
# layer_ar, layer_fsm, llama_engine_axi, matmul, matvec_engine, sampler and
# seq_ctrl.  Leaving tb/ out meant a headline "42 PASS" that quietly excluded a
# quarter of rtl/.
#
# They are run as separate suites rather than merged into one list, because:
#
#   * they are different generations of the design and a failure in the older
#     one means something different from a failure in the current one.  The
#     summary is printed PER SUITE as well as overall.
#   * they use opposite conventions for data files.  Every path in tb/ is
#     "../mem/golden/...", while sim/ mostly opens bare vector names in the
#     working directory.  One workdir layout serves both, but only because it
#     provides both forms.
#   * SEVEN testbench names exist in both: tb_embed, tb_lm_head, tb_matmul_rt,
#     tb_rmsnorm, tb_rope, tb_softmax and tb_swiglu are each declared by a tb/
#     file and by a sim/tb_*_ps.vhd file.  Every key in this script is
#     therefore <suite>:<name>, and the scratch directories are keyed the same
#     way, or the two suites would share a GHDL library.
#
# --suite selects one; the default runs both.  A tb/ testbench that cannot be
# run is reported SKIPPED with its reason, exactly like an xsim-only one, and
# never fails the run silently.
#
# ---------------------------------------------------------------------------
# WARNING: DO NOT EDIT THIS FILE WHILE A RUN OF IT IS IN PROGRESS
# ---------------------------------------------------------------------------
# bash reads a script lazily, by BYTE OFFSET, as it executes.  Editing the file
# under a running instance shifts every offset after the edit, and the shell
# resumes mid-token somewhere it was never meant to be.  This happened during
# bring-up: a run produced a full, correct-looking set of per-test results and
# then died with "syntax error near unexpected token `fi'" at a line that is
# perfectly valid, having silently skipped the summary.  The per-test results
# were fine and the conclusion was missing, which is the worst combination.
# Copy the file elsewhere and edit that, or wait for the run to finish.
#
# ---------------------------------------------------------------------------
# THE THINGS THIS GETS RIGHT, AND WHY EACH ONE IS HERE
# ---------------------------------------------------------------------------
#
# 1. GHDL HERE IS THE MCODE BACKEND.  `ghdl -e` produces NO binary and exits 0.
#    A runner built on `-e && ./tb` therefore reports a green build and runs
#    nothing.  This has already cost this project time; see the header of
#    sim/run_gdn_block.sh.  `ghdl -r <entity>` is run directly, always.
#
#    Related trap, and it bit this script during bring-up: the top-level entity
#    is NOT always the file stem.  sim/tb_rope_ps.vhd declares `entity tb_rope`,
#    sim/tb_rmsnorm_ps.vhd declares `entity tb_rmsnorm`, and five others do the
#    same.  Running the stem gives "cannot find entity or configuration", which
#    reads like a broken analysis.  The entity name is parsed out of the file.
#
# 2. ANALYSIS ORDER IS DERIVED, NOT LISTED.  A hardcoded order rots the moment
#    somebody adds a package.  Every rtl/, sim/ and sim/micro/ source is parsed
#    for the design units it DEFINES (entity/package) and the ones it
#    REFERENCES (`use work.X`, `entity work.X`, and component instantiation),
#    and the per-testbench closure is emitted in topological order.  The only
#    hardcoded part is a tie-break that pulls fixed_luts_pkg, fixed_pkg,
#    util_pkg and model_cfg_pkg to the front when the graph leaves them
#    unordered relative to each other; every real edge still comes from the
#    files.  A dependency cycle is reported as a SKIP, not silently ignored.
#
# 3. -frelaxed IS PASSED TO BOTH -a AND -r, UNCONDITIONALLY.  tb_rmsnorm_bf
#    uses non-protected shared variables; giving the flag to `-a` alone leaves
#    `-r` re-elaborating (mcode elaborates at run time) and failing with
#    analysis errors and no simulation, which reads as a broken testbench.
#    Detecting the need per file is possible but pointless: -frelaxed relaxes
#    LRM strictness, it does not change simulation semantics and it cannot
#    suppress an assertion, so applying it everywhere is strictly safer than
#    any list and cannot rot.  Same reasoning for --max-stack-alloc=0, which
#    several testbenches need because they build their vector tables as
#    function-local temporaries and ghdl-mcode's 128 KB default rejects them
#    with "declaration of a too large object" rather than a VHDL error.
#
# 4. EVERY TEST GETS ITS OWN WORKING DIRECTORY, POPULATED.  Testbenches open
#    vector files by bare name ("gdn_emit_chain_vec.txt") and golden files as
#    "../mem/golden/...".  Run from the wrong place they abort with "cannot
#    open vectors", which is a spurious failure.  Each test runs in
#    $SCRATCH/<tb>/run with every non-VHDL file in sim/ symlinked in and
#    $SCRATCH/<tb>/mem -> $REPO/mem, so both forms resolve.  That is also what
#    makes parallelism safe: no two tests share a workdir or a GHDL library.
#    Nothing is ever written into sim/.
#
# 5. GENERICS, STOP-TIMES AND GENERATED VECTORS ARE LIFTED FROM THE EXISTING
#    SCRIPTS, not reinvented.  See the EXTRAS tables below; each row cites the
#    run_*.sh or mutate_*.sh it came from.  Six vector files are NOT committed
#    and are produced by a C generator in ref/; those are built into the test's
#    own workdir.  A testbench whose vector file is missing and whose generator
#    is not in the table is still handled: the vector name is parsed out of the
#    testbench and ref/<stem>.c is built with its own defaults.  That is what
#    lets a testbench added by another workstream today run without an edit
#    here -- tb_attn_twiddle appeared mid-development and needed no row.
#
# 6. A VERDICT COMES FROM EVIDENCE, NOT FROM AN EXIT CODE ALONE.  This repo has
#    had an assertion at `severity note`: a genuine defect printed and the run
#    exited 0 (sim/tb_b_audit_ser_handshake.vhd line 203 documents the case).
#    A test is PASS only if it exits 0, prints NO failure marker, AND prints a
#    recognised success marker.  A run that produces no output at all is a
#    FAILURE, not a pass.  A run that produces output with no trustworthy
#    marker either way is NOVERDICT and counted as a failure -- it is not
#    evidence of anything.  Four testbenches in this repo are genuinely not
#    self-checking (they dump values for the netlist-compare flow, or measure
#    cycles); they are declared NOCHECK below, with the reason, and are
#    reported in their own bucket rather than being quietly counted as passes.
#
#    The inverse mistake is guarded too.  A line that reports a failure COUNT
#    of zero is not a failure: tb/tb_divider_rs ends a clean run with
#    "DIVIDER TB RESULT: PASS=608 FAIL=0", and a bare \bFAIL\b match called
#    that a failed test until the neutralisation in the judge was added.  Only
#    ZERO-valued counters are neutralised, and only on the failure scan.
#
# 7. TIMEOUTS ARE REPORTED SEPARATELY FROM FAILURES.  They mean different
#    things: a timeout is usually an unguarded clock or a deadlock, a failure
#    is usually arithmetic.  Four testbenches in this project once ran forever
#    on an unguarded clock, one of them for 4h58m at 99.5% CPU.
#
# 8. EVERY RESULT LINE CARRIES ITS ELAPSED SECONDS.  Not decoration: --quick's
#    exclusion list is only honest if it was chosen from measurement, and the
#    one slow test in a twenty-minute run is the first thing anyone wants to
#    know.  It is also what caught the SLOW_SET bug -- --quick was running a
#    408 s testbench it was documented as excluding.
#
# 9. THE SCRIPT RUNS FROM A PRIVATE COPY OF ITSELF.  bash reads a script by
#    byte offset as it executes, so an edit to sim/regress.sh corrupts any run
#    already in flight -- and with several agents in this repo, the one who
#    gets hit is not the one who edited it.  It happened three times during
#    this script's own development, once to a third party.  A comment could
#    not fix that, so section 0 copies the file to a private temp path and
#    re-execs it; from then on the running process reads a file nobody else
#    can name.  Arguments pass through, the exit status is the payload's
#    because `exec` replaces the process, the repo root is resolved BEFORE the
#    re-exec and exported, and the copy is syntax-checked first in case it was
#    taken mid-write.  Editing sim/regress.sh during a run is now merely
#    pointless rather than destructive.
#
# 10. THE PASS COUNT HAS A FLOOR.  Every other check here watches for a test
#    going RED; a test that goes MISSING makes the suite GREENER and nothing
#    would have noticed.  BASELINE_PASS is checked on full unfiltered runs and
#    fails the run when the count DROPS, saying in as many words that this is
#    a disappearance and not a failure.
#
# 11. PARALLELISM IS CONSERVATIVE BY DEFAULT.  --jobs defaults to 2 because this
#    workstation regularly has a Vivado synthesis running, and Vivado is the
#    memory hog that has already triggered a systemd-oomd kill of the whole
#    session cgroup.  Raise it when the box is idle.
#
# ---------------------------------------------------------------------------
# WHAT --quick SKIPS, AND WHY.  --quick IS NOT COVERAGE.
# ---------------------------------------------------------------------------
# --quick runs the fast unit testbenches only.  MEASURED at --jobs 2 with a
# Vivado place-and-route competing for the box: 45 s wall, 48 PASS + 3 NOCHECK,
# slowest single test 7 s; against 1069 s for the full both-suite run in the
# same conditions.  Wall time swings a lot with machine load, so treat those as
# ratios rather than budgets.  --quick exists for the minute before a commit
# and it is NOT a substitute for a full run.  It deliberately omits, by name:
#
#   tb_gdn_block                the six-unit top level, minutes per skew point
#   tb_gdn_emit_chain           four units and four seams
#   tb_gdn_recur_pipe           384 cases at DIM=128
#   tb_gdn_y_emit               24 heads x 128 elements over two blocks
#   tb_engine_dump              the whole shared-datapath engine, token loop
#   tb_matvec_int4              full AXI weight-stream end to end
#   tb_matvec_axi               the PS register-map sequence
#   tb_matvec_core              trace-driven, thousands of trace lines
#   tb_gdn_conv_cycles          CH_MAX=3072 cycle accounting
#   tb_b_audit_ser_handshake    serialiser handshake audit over 3 blocks
#   tb_hbm_tg                   HBM traffic generator, long burst program
#   tb_llama_top                the integration top level: the whole D core,
#                               the real matvec_int4 over five AXI masters and
#                               the real gdn_block, 4 blocks x 4 descriptor-
#                               memory latencies.  MEASURED 86 s, which would
#                               nearly triple --quick on its own.
#   tb_llama_top_seq            the same integration top level at the
#                               multi-token KV-cache configuration: four
#                               tokens of one sequence through the real
#                               rtl/attn_kv_axi.vhd over three modelled AXI
#                               slaves, two attention layers, two latency
#                               points.  MEASURED 302 s through this runner.
#   tb_llama_top_real           the same integration top level with EVERY
#                               computing unit real AND real Qwen3.5-9B
#                               weights: real matvec_int4, real gdn_block,
#                               real attn_block, real rmsnorm_rs on the D-vec
#                               norm op, weights from the committed
#                               sim/llama_top_w_b4_pool.hex.  MEASURED 75 s
#                               through this runner (127 s standalone on a
#                               box that was running nine other simulations).
#                               Until this row existed the gate ran ONLY the
#                               generic defaults, which are the attention STUB
#                               and the probe norm.
#   tb_seq_desc_fetch           491-descriptor walk
#   tb_seq_opdec                491-step walk through three units
#   tb_seq_region_lock          491-step plan
#
# tb_seq_vec_seam is deliberately NOT on that list even though it is a seam
# test: five real units, but a short synthetic schedule, so it runs in about
# two seconds and there is no reason to lose the seam coverage in --quick.
#
# and from the tb/ suite:
#
#   tb_e2e                      seq_ctrl over 16 tokens, all layers
#   tb_engine                   24 tokens through the whole engine
#   tb_engine_shared            24 tokens through the shared datapath
#   tb_engine_dbg               the same, as a register dump
#   tb_llama_engine_axi         24 tokens through the AXI register map
#   tb_layer, tb_layer_fsm      a whole layer, weights loaded from mem/
#   tb_matmul, tb_weights_pkg   both pull in rtl/weights_pkg.vhd, 1.9 MB of
#                               constants whose ANALYSIS is the slow part
#
# Those are exactly the ones that cover the SEAMS between units, which is where
# the cross-subsystem regressions live.  Never conclude "regression is green"
# from a --quick run.
#
# ---------------------------------------------------------------------------
# WHAT IS SKIPPED AND WHY, IN A FULL RUN
# ---------------------------------------------------------------------------
# Nothing is dropped quietly.  Every testbench appears in the output with a
# verdict, and a testbench that cannot be run is printed as SKIPPED with its
# reason.  There are three automatically-detected reasons:
#
#   (a) the testbench declares `library beh` -- it is a post-synthesis
#       netlist-versus-behavioral comparison and needs TWO libraries plus
#       UNISIM/SECUREIP, which is Vivado xsim, not GHDL.  Run those with the
#       matching sim/run_*_cmp.sh after regenerating the netlist.
#   (b) the testbench's closure needs a design unit that only a netlist-side
#       file provides (post_*.vhd, *_net*.vhd, *_ps_wrap*.vhd).  Same reason.
#   (c) the closure names a design unit nothing in rtl/, sim/ or sim/micro/
#       defines.  That is a real hole and it is named in the output.
#
# Both suites are in scope, so "no testbench" in the coverage section means no
# testbench anywhere.  The coverage report also names the files only the tb/
# suite reaches, because those are the ones that go untested if somebody runs
# with --suite sim out of habit.
# ---------------------------------------------------------------------------
set -uo pipefail

# ===========================================================================
# 0. SELF-ISOLATION.  Run from a PRIVATE COPY, so an edit to sim/regress.sh
#    cannot corrupt a run that is already in flight.
# ===========================================================================
# bash reads a script lazily, by BYTE OFFSET, as it executes.  Editing the file
# under a running instance shifts every offset after the edit and the shell
# resumes mid-token.  The symptom is a full, correct-looking set of per-test
# results followed by "syntax error" at a line that is perfectly valid, with
# the summary silently missing -- results without a conclusion, which is the
# worst of the possible failures.
#
# A comment warning about it was not enough, and could not be: with several
# agents sharing this repo, the one who gets hit is not the one who edited the
# file.  So the script copies itself somewhere private and re-execs that copy.
# From then on the running process is reading a file nobody else can name.
#
# Four things this has to get right, all easy to get subtly wrong:
#
#   * ARGUMENTS.  `exec ... "$@"` passes them through unchanged, including
#     empty ones and ones containing spaces.  --list, --only, --suite and the
#     rest behave identically either side of the re-exec.
#   * EXIT STATUS.  `exec` REPLACES this process, so the payload's status is
#     the status the caller sees.  There is no wrapper left to mask it.  That
#     matters more here than usual: the whole value of this runner is that a
#     non-zero exit means something.
#   * PATHS.  Everything below derives from $REPO, and $REPO derives from
#     ${BASH_SOURCE[0]}, which after the re-exec points at /tmp.  So the repo
#     root is resolved HERE, from the original location, and exported.  Get
#     this wrong and the copy resolves rtl/ and sim/ somewhere they are not.
#   * A HALF-WRITTEN SOURCE.  If the copy happens to be taken while somebody
#     is mid-write, the copy is garbage and re-execing it would produce
#     exactly the failure this guard exists to prevent.  `bash -n` on the copy
#     refuses that case loudly instead.
#
# REGRESS_NO_REEXEC=1 disables the guard, for debugging the guard itself.
if [ -z "${REGRESS_REPO:-}" ]; then
  REGRESS_REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)" || exit 2
  export REGRESS_REPO
fi

if [ -z "${REGRESS_SELF:-}" ] && [ -z "${REGRESS_NO_REEXEC:-}" ]; then
  _self="$(mktemp -t regress-self.XXXXXXXX.sh)" || exit 2
  if ! cat "${BASH_SOURCE[0]}" > "$_self"; then
    rm -f "$_self"; echo "regress.sh: could not take a private copy" >&2; exit 2
  fi
  if ! "${BASH:-/bin/bash}" -n "$_self" 2>/dev/null; then
    rm -f "$_self"
    echo "regress.sh: the private copy does not parse -- sim/regress.sh was" >&2
    echo "  probably being written at the instant it was copied.  Try again." >&2
    exit 2
  fi
  chmod 0700 "$_self"
  export REGRESS_SELF="$_self"
  exec "${BASH:-/bin/bash}" "$_self" "$@"
  # Only reached if exec itself failed.
  rm -f "$_self"
  echo "regress.sh: could not re-exec the private copy" >&2
  exit 2
fi

REPO="$REGRESS_REPO"
SIM="$REPO/sim"

# The cleanup trap is armed HERE, before option parsing, not later next to the
# scratch directory.  --help and an unknown option both exit during parsing,
# and a trap armed after that point leaks a private copy into /tmp every time
# somebody types --help.  ${SCRATCH:-} and ${KEEP:-0} are not yet set at this
# point, hence the defaults.
cleanup() {
  [ -n "${REGRESS_SELF:-}" ] && rm -f "$REGRESS_SELF"
  [ "${KEEP:-0}" = 0 ] && [ -n "${SCRATCH:-}" ] && rm -rf "$SCRATCH"
  return 0
}
trap cleanup EXIT
GHDL="${GHDL:-ghdl}"
STD="--std=08"
RELAX="-frelaxed"

JOBS=2
TIMEOUT=900
QUICK=0
ONLY=""
LIST_ONLY=0
COVERAGE_ONLY=0
KEEP=0
SUITES="sim tb"

# ---------------------------------------------------------------------------
# THE BASELINE FLOOR.  A test that DISAPPEARS makes the suite greener.
# ---------------------------------------------------------------------------
# Everything else in this script watches for a test going RED.  Nothing watched
# for a test going MISSING, and the two are different failures: a testbench
# deleted, renamed out of the tb_*.vhd glob, or newly unresolvable and so
# reported SKIPPED, REMOVES a red line rather than adding one.  The headline
# then reads greener than the day before while covering less, which is the one
# way this runner could mislead the project it gates.
#
# So the gate has a floor.  It is a FLOOR, not an equality: adding a testbench
# must not fail the run, it prints a note asking for the floor to be raised.
# Dropping below it fails the run, and says explicitly that this is a
# disappearance rather than a failure, because the fix is completely different.
#
# Raise this whenever a testbench is added.  It is checked ONLY on a full,
# unfiltered both-suite run -- --quick, --only and --suite all legitimately
# pass fewer, and a floor that fired on those would be noise inside a week.
BASELINE_PASS=83   # +1 sim/tb_llama_top_real, the integration top level with
                   #    C_REAL, NORM_REAL and the committed real-weight image
                   #    all on.  Before it, EVERY tb_llama_top gate row
                   #    elaborated with the attention stub and the probe norm,
                   #    so a regression in the real path left the gate green.
                   #    Its vector sim/llama_top_w_b4_pool.hex is COMMITTED --
                   #    the generator needs an 18 GB GGUF that is not in git --
                   #    so it needs no row in the vector tables, 2026-08-29
                   # +1 sim/tb_llama_top_seq, rtl/llama_top.vhd joined to
                   #    rtl/attn_kv_axi.vhd over a multi-token sequence.  It
                   #    is a WRAPPER around sim/tb_llama_top.vhd, because this
                   #    script keys a test by name and cannot run one
                   #    testbench at two generic sets, 2026-08-29
                   # +1 sim/tb_attn_kv_seam, rtl/attn_block.vhd joined to
                   #    rtl/attn_kv_axi.vhd over a 4-token sequence, 2026-08-28
                   # +1 sim/tb_mv4i_desc_image, the gateware judging a
                   #    descriptor image written by tools/gen_mv4i_desc.py.
                   #    Its vector sim/mv4i_desc_image.txt is COMMITTED, so it
                   #    needs no row in this script and no model set, 2026-08-28
                   # +1 sim/tb_matvec_fk33_desc, subsystem A through the
                   #    descriptor control plane plus its mutation matrix,
                   #    2026-08-28
                   # +1 sim/tb_matvec_fk33, subsystem A at ROWS_IF=48 /
                   #    AXI_DW=256 from a real .mv4i file, 2026-08-28
                   # +1 sim/tb_llama_top, the integration top level, 2026-08-28
                   # +1 sim/tb_weight_streamer, 6.5a reassembly, 2026-08-28
                   # +1 sim/tb_attn_mac_array, subsystem C's MAC array, 2026-08-28
                   # +1 sim/tb_attn_block, subsystem C's top level, 2026-08-28
                   # +1 sim/tb_attn_kv_axi, subsystem C's KV cache in HBM at
                   #    two AXI widths, 2026-08-28

usage() { sed -n '2,237p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; exit 0; }

while [ $# -gt 0 ]; do
  case "$1" in
    --quick)     QUICK=1; shift ;;
    --jobs)      JOBS="$2"; shift 2 ;;
    --jobs=*)    JOBS="${1#*=}"; shift ;;
    --timeout)   TIMEOUT="$2"; shift 2 ;;
    --timeout=*) TIMEOUT="${1#*=}"; shift ;;
    --only)      ONLY="$2"; shift 2 ;;
    --only=*)    ONLY="${1#*=}"; shift ;;
    --list)      LIST_ONLY=1; shift ;;
    --coverage)  COVERAGE_ONLY=1; shift ;;
    --suite)     SUITES="$2"; shift 2 ;;
    --suite=*)   SUITES="${1#*=}"; shift ;;
    --keep)      KEEP=1; shift ;;
    -h|--help)   usage ;;
    *) echo "regress.sh: unknown option '$1' (try --help)" >&2; exit 2 ;;
  esac
done

command -v "$GHDL" >/dev/null 2>&1 || { echo "regress.sh: ghdl not found on PATH" >&2; exit 2; }

SCRATCH="${REGRESS_SCRATCH:-$(mktemp -d -t regress.XXXXXX)}"
mkdir -p "$SCRATCH"
# The trap is already armed (see cleanup() above).  --keep governs the per-test
# scratch tree, which is evidence; it never keeps the private copy, which is
# not.
[ "$KEEP" = 1 ] && echo "scratch: $SCRATCH"

# --quick's exclusion list, keyed <suite>:<name>.  Suite-qualified because the
# two suites share SEVEN testbench names: tb_embed, tb_lm_head, tb_matmul_rt,
# tb_rmsnorm, tb_rope, tb_softmax and tb_swiglu are each declared by a tb/ file
# AND by a sim/tb_*_ps.vhd file.  A bare name would match both.
SLOW_TBS="sim:tb_gdn_block sim:tb_gdn_emit_chain sim:tb_gdn_recur_pipe
          sim:tb_gdn_y_emit sim:tb_engine_dump sim:tb_matvec_int4
          sim:tb_matvec_axi sim:tb_matvec_core sim:tb_gdn_conv_cycles
          sim:tb_b_audit_ser_handshake sim:tb_hbm_tg sim:tb_seq_desc_fetch
          sim:tb_seq_opdec sim:tb_seq_region_lock sim:tb_llama_top
          sim:tb_llama_top_seq sim:tb_llama_top_real
          tb:tb_e2e tb:tb_engine tb:tb_engine_shared tb:tb_engine_dbg
          tb:tb_llama_engine_axi tb:tb_layer tb:tb_layer_fsm tb:tb_matmul
          tb:tb_weights_pkg"
# NORMALISED to single-space separated, and this is load bearing.  SLOW_TBS is
# written across several lines for readability, so the separator between the
# last entry on one line and the first on the next is a NEWLINE.  A membership
# test of the form  [[ " $SLOW_TBS " == *" $key "* ]]  then silently fails for
# every entry that happens to sit at a line end, and those tests run anyway.
# That is not hypothetical: it is why --quick was 452 s -- tb:tb_engine_dbg sat
# at a line end, was never excluded, and cost 408 s of the 452 on its own.
SLOW_SET=" $(echo $SLOW_TBS) "

# ===========================================================================
# 1. PLAN.  Parse every source, resolve each testbench's closure, order it.
#    Emits, per testbench:  name  status  reason  files  top-entity  vectors
# ===========================================================================
PLAN="$SCRATCH/plan.tsv"
COVER="$SCRATCH/coverage.txt"

python3 - "$REPO" "$PLAN" "$COVER" <<'PYEOF'
import re, os, sys, glob

repo, plan_out, cover_out = sys.argv[1], sys.argv[2], sys.argv[3]

# Netlist-side artefacts.  These are post-synthesis outputs (write_vhdl
# -mode funcsim) and the thin wrappers that give them their PS-facing port
# profile.  They are UNISIM/SECUREIP structural netlists: GHDL has no such
# libraries, so anything that needs one is an xsim job, not a GHDL job.
# This is a NAMING CONVENTION rule, deliberately, and it is the only
# hardcoded classification in the plan.  sim/rope_ps_rtl.vhd is the one
# hand-written RTL stand-in for such a wrapper and is correctly not matched.
NETLIST_RE = re.compile(r'^(post_.*|.*_net(_ren)?|.*_ps_wrap\d*|attn_net_wrap|attn_probe_wrap)\.vhd$')

def strip(src):
    """Drop VHDL comments without disturbing string literals or line count."""
    lines = []
    for ln in src.split('\n'):
        out, i, instr = [], 0, False
        while i < len(ln):
            c = ln[i]
            if c == '"':
                instr = not instr
            if not instr and c == '-' and i + 1 < len(ln) and ln[i+1] == '-':
                break
            out.append(c); i += 1
        lines.append(''.join(out))
    return '\n'.join(lines)

def parse(path):
    raw = strip(open(path, errors='replace').read())
    txt = raw.lower()

    entities = re.findall(r'^[ \t]*entity[ \t]+(\w+)[ \t]+is', txt, re.M)
    defines = set(entities)
    defines |= set(re.findall(r'^[ \t]*package[ \t]+(?!body\b)(\w+)[ \t]+is', txt, re.M))

    refs = set()
    refs |= set(re.findall(r'\buse[ \t]+work\.(\w+)', txt))
    refs |= set(re.findall(r'\bentity[ \t]+work\.(\w+)', txt))
    refs |= set(re.findall(r'\bfor[ \t]+[\w,\s]+:[ \t]*\w+[ \t]+use[ \t]+entity[ \t]+work\.(\w+)', txt))
    # Component instantiation:  label : name [generic map|port map].  The name
    # may sit on its own line, so the match crosses the newline.
    refs |= set(re.findall(r'\n[ \t]*\w+[ \t]*:[ \t]*(\w+)[ \t\n]*(?:generic[ \t]+map|port[ \t]+map)', txt))
    # A component declared and bound by default binding still needs its entity.
    refs |= set(re.findall(r'^[ \t]*component[ \t]+(\w+)', txt, re.M))

    for kw in ('process', 'block', 'if', 'for', 'case', 'while', 'null',
               'entity', 'configuration', 'others', 'work', 'generate'):
        refs.discard(kw)
    refs -= defines

    # Data files opened by bare name (no directory part).  "../mem/golden/..."
    # is deliberately excluded: those are committed golden files reached
    # through the per-test workdir's mem symlink, not generated vectors.
    vecs = set()
    for lit in re.findall(r'"([^"\n]+)"', raw):
        if lit.endswith('.txt') and '/' not in lit and ' ' not in lit:
            vecs.add(lit)
    return defines, refs, entities, sorted(vecs)

# tb/ comes LAST so that, on the seven names both suites declare, the sim/
# file wins the `provider` slot.  It never matters in practice -- a testbench
# entity is referenced by nothing -- but a deterministic rule beats a lucky one.
sources = []
for pat in ('rtl/*.vhd', 'sim/*.vhd', 'sim/micro/*.vhd', 'tb/*.vhd'):
    sources += sorted(glob.glob(os.path.join(repo, pat)))

files = {}          # relpath -> (defines, refs, entities, vecs)
provider = {}       # design unit -> relpath  (first non-netlist wins)
netlist_provider = {}
for p in sources:
    rel = os.path.relpath(p, repo)
    base = os.path.basename(p)
    files[rel] = parse(p)
    isnet = bool(NETLIST_RE.match(base))
    for name in files[rel][0]:
        if isnet:
            netlist_provider.setdefault(name, rel)
        elif name not in provider:
            provider[name] = rel

PIN = ['rtl/fixed_luts_pkg.vhd', 'rtl/fixed_pkg.vhd', 'rtl/util_pkg.vhd',
       'rtl/model_cfg_pkg.vhd']

def closure_of(relpath):
    """Transitive closure over the non-netlist provider set."""
    got, netonly, missing = set(), set(), set()
    stack = [relpath]
    while stack:
        f = stack.pop()
        if f in got:
            continue
        got.add(f)
        for r in files[f][1]:
            if r in provider:
                stack.append(provider[r])
            elif r in netlist_provider:
                netonly.add(r)
            else:
                missing.add(r)
    return got, netonly, missing

def toposort(closure, last):
    dep = {}
    for f in closure:
        dep[f] = set()
        for r in files[f][1]:
            q = provider.get(r)
            if q and q in closure and q != f:
                dep[f].add(q)
    ordered, done = [], set()
    pending = [p for p in PIN if p in closure] + \
              sorted(f for f in closure if f not in PIN)
    while pending:
        rest, progressed = [], False
        for f in pending:
            if dep[f] <= done:
                ordered.append(f); done.add(f); progressed = True
            else:
                rest.append(f)
        pending = rest
        if not progressed:
            return None, pending
    return [f for f in ordered if f != last] + [last], []

