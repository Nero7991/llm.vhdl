        if netonly:
            who = sorted(netonly)
            rows.append((name, suite, 'SKIP',
                         'needs %s, provided only by a post-synthesis netlist file (%s): '
                         'xsim job, not GHDL' % (', '.join(who), netlist_provider[who[0]]),
                         '', '', ''))
