        rv="FAIL"; rs="?"; rd="the runner produced no result file for this test"
      fi
      printf '%-10s %-34s %5ss  %s\n' "$rv" "$k" "$rs" "$rd"
      case "$rv" in
        PASS)      npass=$((npass+1)); sp[$q]=$(( ${sp[$q]} + 1 )) ;;
        NOCHECK)   nnoc=$((nnoc+1));   sn[$q]=$(( ${sn[$q]} + 1 )) ;;
        TIMEOUT)   ntime=$((ntime+1)); st[$q]=$(( ${st[$q]} + 1 )); failed_list+=("$k (timeout)") ;;
        ERROR)     nerr=$((nerr+1));   se[$q]=$(( ${se[$q]} + 1 )); failed_list+=("$k (build error)") ;;
        NOVERDICT) nnov=$((nnov+1));   sv[$q]=$(( ${sv[$q]} + 1 )); failed_list+=("$k (no verdict)") ;;
        *)         nfail=$((nfail+1)); sf[$q]=$(( ${sf[$q]} + 1 )); failed_list+=("$k") ;;
      esac
    done
    echo
  done

  echo
  echo "-- SKIPPED (listed, never dropped silently) ------------------------------------"
  if [ "${#skipped_names[@]}" = 0 ]; then
    echo "(none)"
  else
    for i in "${!skipped_names[@]}"; do
      printf 'SKIPPED    %-34s %s\n' "${skipped_names[$i]}" "${skipped_reasons[$i]}"
    done
  fi

  report_not_in_git
fi

# ===========================================================================
# 5. COVERAGE: RTL with no testbench anywhere
# ===========================================================================
echo
echo "-- RTL COVERAGE ----------------------------------------------------------------"
echo "   (transitive closure from every testbench in BOTH suites)"
tot=$(awk '/^TOTAL_RTL/{print $2}' "$COVER")
unc=$(awk '/^UNCOVERED/{print $2}' "$COVER")
bys=$(awk '/^BYSIM/{print $2}' "$COVER")
byt=$(awk '/^BYTB/{print $2}' "$COVER")
byb=$(awk '/^BYBOTH/{print $2}' "$COVER")
printf '   %d files in rtl/: %d reached by the sim/ suite, %d by tb/, %d by both.\n' \
       "$tot" "$bys" "$byt" "$byb"
echo
echo "   RTL FILES REACHED BY NO TESTBENCH IN EITHER SUITE:"
if grep -q '^NOTB ' "$COVER"; then
  awk '/^NOTB /{print "     " $2}' "$COVER"
else
  echo "     (none)"
fi
echo "   $unc of $tot."
if grep -q '^TBONLY' "$COVER"; then
  echo
  echo "   reached ONLY by the tb/ suite (run it with --suite tb, or leave the"
  echo "   default which runs both):"
  awk '/^TBONLY /{printf "     %-32s %s\n", $2, $3}' "$COVER"
fi

[ "$COVERAGE_ONLY" = 1 ] && exit 0

# ---- the baseline floor, full unfiltered runs only ------------------------
baseline_note=""
baseline_drop=0
if [ "$QUICK" = 0 ] && [ -z "$ONLY" ] && [ "$(echo $SUITES)" = "sim tb" ]; then
  if [ "$npass" -lt "$BASELINE_PASS" ]; then
    baseline_drop=1
    baseline_note="BASELINE DROP: $npass passing, expected at least $BASELINE_PASS"
  elif [ "$npass" -gt "$BASELINE_PASS" ]; then
    # THE ONE PLACE THE DOUBLE-COUNT COULD COME BACK.  "You are above the floor,
    # raise it" is correct advice on a clean tree and WRONG advice on a tree
    # carrying rows nobody else has -- following it is literally how 101 was
    # arrived at.  So the advice is withheld exactly when it would be wrong.
    if [ -n "$UNTRACKED_ROWS$IGNORED_ROWS$OPTIONAL_ROWS" ]; then
      baseline_note="baseline: $npass passing, above the floor of $BASELINE_PASS -- but this tree has rows a clean checkout does not get:$UNTRACKED_ROWS$IGNORED_ROWS$OPTIONAL_ROWS.  DO NOT raise BASELINE_PASS from this run: the floor is a CLEAN-CHECKOUT number, and a floor raised to include rows that depend on your working tree or your model set is unreachable for everybody else, including you after a clean clone."
    else
      baseline_note="baseline: $npass passing, above the recorded floor of $BASELINE_PASS -- raise BASELINE_PASS in this script"
    fi
  else
    baseline_note="baseline: $npass passing, matches the recorded floor of $BASELINE_PASS"
  fi
fi

echo
echo "================================================================================"
for q in $SUITES; do
  printf ' suite %-4s  PASS %d   FAIL %d   NOVERDICT %d   TIMEOUT %d   BUILD-ERROR %d   NOCHECK %d\n' \
    "$q" "${sp[$q]}" "${sf[$q]}" "${sv[$q]}" "${st[$q]}" "${se[$q]}" "${sn[$q]}"
done
printf ' OVERALL     PASS %d   FAIL %d   NOVERDICT %d   TIMEOUT %d   BUILD-ERROR %d   NOCHECK %d   SKIPPED %d\n' \
  "$npass" "$nfail" "$nnov" "$ntime" "$nerr" "$nnoc" "${#skipped_names[@]}"
echo "================================================================================"
if [ -n "$baseline_note" ]; then
  echo " $baseline_note"
  if [ "$baseline_drop" = 1 ]; then
    echo "   Nothing went red.  Something went MISSING: a testbench was deleted,"
    echo "   renamed out of the tb_*.vhd glob, or has become unresolvable and is"
    echo "   now being reported SKIPPED.  Check the SKIPPED list above against"
    echo "   git, then either restore the test or lower BASELINE_PASS on purpose."
  fi
  echo "================================================================================"
fi
if [ "${#failed_list[@]}" -gt 0 ] || [ "$baseline_drop" = 1 ]; then
  if [ "${#failed_list[@]}" -gt 0 ]; then
    echo " NOT GREEN:"
    for f in "${failed_list[@]}"; do echo "   - $f"; done
    echo
  fi
  echo " REGRESSION: FAIL"
  exit 1
fi

echo " REGRESSION: PASS"
exit 0
