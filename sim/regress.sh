    sim:tb_swchain_beh)     echo 'observation only: prints one o_exp/checksum line. Its header says "GHDL-only sanity bench"; the real check is tb_swchain_cmp under xsim' ;;
    sim:tb_rms_sweep)       echo 'observation only: sweeps xe and prints oe/o0, then SWEEP_DONE. Has no pass criterion; it exists to compare against a recorded hardware reading' ;;
    sim:tb_gdn_conv_cycles) echo 'measurement only: emits a CSV cycle table (CYC,...) and "done". There is no expected value to check it against' ;;
    # tb/tb_engine_dbg has ZERO assertions and zero severity error/failure: it
    # is a register-dump debug harness that reports at severity note and then
    # calls finish, so it exits 0 no matter how broken the design is.  Exactly
    # the hazard clause 6 exists for.
    tb:tb_engine_dbg) echo 'debug register dump: zero assertions, every report at severity note, exits 0 unconditionally. Running it proves it elaborates and terminates, nothing more' ;;
    *) : ;;
  esac
}

# ===========================================================================
# 3. VERDICT.  See point 6 of the header.
# ===========================================================================
# A failure marker anywhere wins over a success marker anywhere.
FAIL_RE='\(assertion (error|failure)\)|\(report (error|failure)\)|:error:|MISMATCH|\bFAIL\b|FAILED|cannot open|error: |simulation failed|DIVERGES|IS NOT|IS WRONG|OUT OF TOLERANCE'
# A success marker must be present or the run is NOVERDICT, never PASS.
# A bare "OK" is deliberately NOT a marker: it is too easy to hit in prose.
PASS_RE='\bPASS\b|\bALL OK\b|all green|0 mismatches|no mismatch|matches ref|bit-exact|bit-identical|within tolerance'

run_one() {   # run_one <suite:name> <top-entity> <vectors-csv> <files...>
  local key="$1" top="$2" vecs="$3"; shift 3
  [ "$vecs" = "-" ] && vecs=""
  local tb="${key#*:}" suite="${key%%:*}"
  # The scratch directory is keyed by the SUITE-QUALIFIED name: tb/tb_rope and
  # sim/tb_rope_ps both elaborate an entity called tb_rope, and a bare-name
  # directory would have the two suites sharing a GHDL library.
  local dir="$SCRATCH/${suite}_${tb}" log="$SCRATCH/${suite}_${tb}/log"
  local run="$dir/run" work="$dir/work"
  local t0; t0=$(date +%s)
  mkdir -p "$run" "$work"
  # Both suites reach golden data as ../mem/... from the run directory.  The
  # tb/ suite uses ONLY that form; sim/ mixes it with bare vector names.
  ln -sfn "$REPO/mem" "$dir/mem"

  # Everything a testbench might open by bare name.  Committed vectors and
  # golden fixtures live in sim/; symlinking keeps them read-only in practice
  # and means nothing is ever written back into the repo.
  local f
  # `.hex` was added 2026-08-29 for sim/llama_top_w_b4_pool.hex, the committed
  # real Qwen3.5-9B weight image sim/tb_llama_top_real.vhd opens by bare name.
  # Without it that row fails with "cannot open the weight image", which reads
  # like a missing file and is a missing GLOB.
  for f in "$SIM"/*.txt "$SIM"/*.dat "$SIM"/*.csv "$SIM"/*.mem "$SIM"/*.bin \
           "$SIM"/*.hex; do
    [ -e "$f" ] && ln -sfn "$f" "$run/$(basename "$f")"
  done
  # tb_matvec_* address their trace one level up, as ../tr.txt.
  for f in "$SIM"/tr.txt "$SIM"/arith_vectors.txt; do
    [ -e "$f" ] && ln -sfn "$f" "$dir/$(basename "$f")"
  done

  # NOTE: a subshell, so that an `exit` on a build failure inside it cannot
  # skip the judging code below.  An earlier revision used a brace group and
  # six tests silently produced no result at all.
  (
    echo "### $key  (top entity: $top)"
    # --- vectors -------------------------------------------------------
    local v stem gen args
    for v in $vecs; do
      stem="${v%.txt}"
      gen="$REPO/ref/$stem.c"
      args="$(tb_vector_args "$v")"
      if [ ! -r "$gen" ]; then
        # No generator.  If sim/ committed one, the symlink above already
        # provides it; otherwise the run will fail loudly on "cannot open".
        continue
      fi
      if [ -e "$SIM/$v" ] && [ -z "$args" ]; then
        continue          # committed, and no curated shape to re-derive
      fi
      if ! cc -O2 -w -I "$REPO/ref" -o "$dir/gen_$stem" "$gen" -lm 2>&1; then
        echo "VECTORGEN_BUILD_FAILED $gen"; exit 90
      fi
      rm -f "$run/$v"
      # shellcheck disable=SC2086
      if ! ( cd "$run" && "$dir/gen_$stem" "$v" $args ) >/dev/null 2>&1; then
        echo "VECTORGEN_RUN_FAILED $gen"; exit 90
      fi
    done

    # --- analysis ------------------------------------------------------
    for f in "$@"; do
      if ! "$GHDL" -a $STD $RELAX --workdir="$work" "$REPO/$f" 2>&1; then
        echo "ANALYSIS_FAILED $f"; exit 91
      fi
    done

    # --- run.  mcode: -e emits nothing, so -r is called directly. -------
    # shellcheck disable=SC2046,SC2086
    ( cd "$run" && timeout -k 5 "$TIMEOUT" \
        "$GHDL" -r $STD $RELAX --workdir="$work" "$top" \
        $(tb_args "$key") --max-stack-alloc=0 2>&1 )
    echo "GHDL_EXIT=$?"
  ) > "$log" 2>&1

  # ---- judge --------------------------------------------------------
  local rc body marker nocheck
  rc=$(grep -oE '^GHDL_EXIT=[0-9]+' "$log" | tail -1 | cut -d= -f2)
  body=$(grep -avE '^(### |GHDL_EXIT=)' "$log")

  # Elapsed seconds are part of the result, not decoration: --quick's exclusion
  # list is only honest if it was chosen from measurement, and the slow test in
  # a 20 minute run is the first thing anyone wants to know.
  verdict() {
    printf '%s\t%s\t%s\t%s\n' "$key" "$1" "$(( $(date +%s) - t0 ))" "$2" \
      > "$SCRATCH/res.${suite}_${tb}"
  }

  if grep -q '^VECTORGEN' "$log"; then
    verdict ERROR "reference vector generator failed: $(grep -m1 '^VECTORGEN' "$log")"; return
  fi
  if grep -q '^ANALYSIS_FAILED' "$log"; then
    verdict ERROR "ghdl -a failed on $(grep -m1 '^ANALYSIS_FAILED' "$log" | cut -d' ' -f2): $(printf '%s' "$body" | grep -aiE 'error' | head -1 | cut -c1-120)"; return
  fi
  [ -n "${rc:-}" ] || rc=1
  if [ "$rc" = "124" ] || [ "$rc" = "137" ]; then
    verdict TIMEOUT "no result within ${TIMEOUT}s -- unguarded clock or deadlock, NOT the same thing as a failure"; return
  fi
  if [ -z "$(printf '%s' "$body" | tr -d '[:space:]')" ]; then
    verdict FAIL "produced NO output at all (exit $rc)"; return
  fi
  local noise; noise="$(tb_expected_noise "$key")"
  if [ -n "$noise" ]; then
    body="$(printf '%s' "$body" | grep -avE "$noise")"
  fi

  # A line that REPORTS A FAILURE COUNT OF ZERO is not a failure.  tb/
  # tb_divider_rs ends a clean run with "DIVIDER TB RESULT: PASS=608 FAIL=0",
  # and a bare \bFAIL\b match calls that a failed test -- which is exactly the
  # inverse of the mistake clause 6 guards against, and just as wrong.  Only
  # ZERO-valued counters are neutralised: "FAIL=3" still matches, and the
  # neutralisation is applied to the FAILURE scan only, never to the success
  # scan, so it cannot manufacture a pass.
  local scan
  scan="$(printf '%s' "$body" | sed -E 's/\b(FAIL|FAILURE|FAILURES|MISMATCH|MISMATCHES|ERROR|ERRORS)[[:space:]]*[=:][[:space:]]*0+\b//g')"
  if [ "$rc" != "0" ]; then
    verdict FAIL "exit $rc: $(printf '%s' "$scan" | grep -aE "$FAIL_RE" | head -1 | cut -c1-160)"; return
  fi
  if printf '%s' "$scan" | grep -aqE "$FAIL_RE"; then
    verdict FAIL "$(printf '%s' "$scan" | grep -aE "$FAIL_RE" | head -1 | cut -c1-160)"; return
  fi

  marker="$(tb_pass_marker "$key")"
  if [ -n "$marker" ]; then
    if printf '%s' "$body" | grep -aqE "$marker"; then
      verdict PASS "$(printf '%s' "$body" | grep -aE "$marker" | head -1 | cut -c1-140)"; return
    fi
    verdict NOVERDICT "ran clean but its declared success marker ('$marker') never appeared"; return
  fi

  nocheck="$(tb_nocheck_reason "$key")"
  if [ -n "$nocheck" ]; then
    verdict NOCHECK "$nocheck"; return
  fi

  if printf '%s' "$body" | grep -aqiE "$PASS_RE"; then
    verdict PASS "$(printf '%s' "$body" | grep -aiE "$PASS_RE" | head -1 | cut -c1-140)"; return
  fi
  verdict NOVERDICT "exit 0 and no failure marker, but NO success marker either -- that is not evidence of a pass"
}

# ===========================================================================
# 4. DRIVE
# ===========================================================================
selected=()
skipped_names=(); skipped_reasons=()
while IFS=$'\t' read -r name suite status reason flist top vecs; do
  key="$suite:$name"
  [[ " $SUITES " == *" $suite "* ]] || continue
  [ -n "$ONLY" ] && [[ "$name" != *"$ONLY"* ]] && continue
  if [ "$status" = "SKIP" ]; then
    skipped_names+=("$key"); skipped_reasons+=("$reason"); continue
  fi
  if [ "$QUICK" = 1 ] && [[ "$SLOW_SET" == *" $key "* ]]; then
    skipped_names+=("$key")
    skipped_reasons+=("--quick: slow seam/top-level test, deliberately excluded -- run without --quick")
    continue
  fi
  # Keep the '-' placeholder: with IFS=tab an EMPTY field collapses and every
  # field after it shifts, which is how the analysis file list once ended up in
  # the vectors slot and every test reported "cannot find entity".
  selected+=("$key"$'\t'"$top"$'\t'"$vecs"$'\t'"$flist")
done < "$PLAN"

if [ "$LIST_ONLY" = 1 ]; then
  echo "== plan =="
  for e in "${selected[@]}"; do
    IFS=$'\t' read -r n t v fl <<< "$e"
    printf 'RUN  %-34s entity=%-24s %2d files  vectors=%s\n' \
           "$n" "$t" "$(echo "$fl" | wc -w)" "$([ "$v" = "-" ] && echo none || echo "$v")"
  done
  for i in "${!skipped_names[@]}"; do
    printf 'SKIP %-34s %s\n' "${skipped_names[$i]}" "${skipped_reasons[$i]}"
  done
  exit 0
fi

if [ "$COVERAGE_ONLY" = 0 ]; then
  echo "================================================================================"
  echo " llama.vhdl regression -- $( [ "$QUICK" = 1 ] && echo 'QUICK subset (NOT coverage)' || echo 'FULL run' ), ${JOBS} job(s), ${TIMEOUT}s per test"
  echo " $(date '+%Y-%m-%d %H:%M:%S')   ghdl: $($GHDL --version | head -1)"
  echo "================================================================================"

  for e in "${selected[@]}"; do
    IFS=$'\t' read -r n t v fl <<< "$e"
    while [ "$(jobs -rp | wc -l)" -ge "$JOBS" ]; do sleep 0.4; done
    # shellcheck disable=SC2086
    run_one "$n" "$t" "$v" $fl &
  done
  wait

  npass=0; nfail=0; ntime=0; nerr=0; nnov=0; nnoc=0
  failed_list=()
  # Per-suite tallies, so a failure in the older generation is never hidden
  # inside a headline number dominated by the current one.
  declare -A sp sf st se sv sn
  for q in $SUITES; do sp[$q]=0; sf[$q]=0; st[$q]=0; se[$q]=0; sv[$q]=0; sn[$q]=0; done
  echo
  for q in $SUITES; do
    printf -- '-- suite %s ---------------------------------------------------------------\n' "$q"
    for e in "${selected[@]}"; do
      k="${e%%$'\t'*}"
      [ "${k%%:*}" = "$q" ] || continue
      rf="$SCRATCH/res.${k%%:*}_${k#*:}"
      if [ -r "$rf" ]; then
        IFS=$'\t' read -r rn rv rs rd < "$rf"
      else
        rv="FAIL"; rs="?"; rd="the runner produced no result file for this test"
      fi
      printf '%-10s %-34s %5ss  %s\n' "$rv" "$k" "$rs" "$rd"
      case "$rv" in
        PASS)      npass=$((npass+1)); sp[$q]=$(( ${sp[$q]} + 1 )) ;;
        NOCHECK)   nnoc=$((nnoc+1));   sn[$q]=$(( ${sn[$q]} + 1 )) ;;
        TIMEOUT)   ntime=$((ntime+1)); st[$q]=$(( ${st[$q]} + 1 )); failed_list+=("$k (timeout)") ;;
        ERROR)     nerr=$((nerr+1));   se[$q]=$(( ${se[$q]} + 1 )); failed_list+=("$k (build error)") ;;
        NOVERDICT) nnov=$((nnov+1));   sv[$q]=$(( ${sv[$q]} + 1 )); failed_list+=("$k (no verdict)") ;;
        *)         nfail=$((nfail+1)); sf[$q]=$(( ${sf[$q]} + 1 )); failed_list+=("$k") ;;
      esac
    done
    echo
  done

  echo
  echo "-- SKIPPED (listed, never dropped silently) ------------------------------------"
  if [ "${#skipped_names[@]}" = 0 ]; then
    echo "(none)"
  else
    for i in "${!skipped_names[@]}"; do
      printf 'SKIPPED    %-34s %s\n' "${skipped_names[$i]}" "${skipped_reasons[$i]}"
    done
  fi
fi

# ===========================================================================
# 5. COVERAGE: RTL with no testbench anywhere
# ===========================================================================
echo
echo "-- RTL COVERAGE ----------------------------------------------------------------"
echo "   (transitive closure from every testbench in BOTH suites)"
tot=$(awk '/^TOTAL_RTL/{print $2}' "$COVER")
unc=$(awk '/^UNCOVERED/{print $2}' "$COVER")
bys=$(awk '/^BYSIM/{print $2}' "$COVER")
byt=$(awk '/^BYTB/{print $2}' "$COVER")
byb=$(awk '/^BYBOTH/{print $2}' "$COVER")
printf '   %d files in rtl/: %d reached by the sim/ suite, %d by tb/, %d by both.\n' \
       "$tot" "$bys" "$byt" "$byb"
echo
echo "   RTL FILES REACHED BY NO TESTBENCH IN EITHER SUITE:"
if grep -q '^NOTB ' "$COVER"; then
  awk '/^NOTB /{print "     " $2}' "$COVER"
else
  echo "     (none)"
fi
echo "   $unc of $tot."
if grep -q '^TBONLY' "$COVER"; then
  echo
  echo "   reached ONLY by the tb/ suite (run it with --suite tb, or leave the"
  echo "   default which runs both):"
  awk '/^TBONLY /{printf "     %-32s %s\n", $2, $3}' "$COVER"
fi

[ "$COVERAGE_ONLY" = 1 ] && exit 0

# ---- the baseline floor, full unfiltered runs only ------------------------
baseline_note=""
baseline_drop=0
if [ "$QUICK" = 0 ] && [ -z "$ONLY" ] && [ "$(echo $SUITES)" = "sim tb" ]; then
  if [ "$npass" -lt "$BASELINE_PASS" ]; then
    baseline_drop=1
    baseline_note="BASELINE DROP: $npass passing, expected at least $BASELINE_PASS"
  elif [ "$npass" -gt "$BASELINE_PASS" ]; then
    baseline_note="baseline: $npass passing, above the recorded floor of $BASELINE_PASS -- raise BASELINE_PASS in this script"
  else
    baseline_note="baseline: $npass passing, matches the recorded floor of $BASELINE_PASS"
  fi
fi

echo
echo "================================================================================"
for q in $SUITES; do
  printf ' suite %-4s  PASS %d   FAIL %d   NOVERDICT %d   TIMEOUT %d   BUILD-ERROR %d   NOCHECK %d\n' \
    "$q" "${sp[$q]}" "${sf[$q]}" "${sv[$q]}" "${st[$q]}" "${se[$q]}" "${sn[$q]}"
done
printf ' OVERALL     PASS %d   FAIL %d   NOVERDICT %d   TIMEOUT %d   BUILD-ERROR %d   NOCHECK %d   SKIPPED %d\n' \
  "$npass" "$nfail" "$nnov" "$ntime" "$nerr" "$nnoc" "${#skipped_names[@]}"
echo "================================================================================"
if [ -n "$baseline_note" ]; then
  echo " $baseline_note"
  if [ "$baseline_drop" = 1 ]; then
    echo "   Nothing went red.  Something went MISSING: a testbench was deleted,"
    echo "   renamed out of the tb_*.vhd glob, or has become unresolvable and is"
    echo "   now being reported SKIPPED.  Check the SKIPPED list above against"
    echo "   git, then either restore the test or lower BASELINE_PASS on purpose."
  fi
  echo "================================================================================"
fi
if [ "${#failed_list[@]}" -gt 0 ] || [ "$baseline_drop" = 1 ]; then
  if [ "${#failed_list[@]}" -gt 0 ]; then
    echo " NOT GREEN:"
    for f in "${failed_list[@]}"; do echo "   - $f"; done
    echo
  fi
  echo " REGRESSION: FAIL"
  exit 1
fi

echo " REGRESSION: PASS"
exit 0
