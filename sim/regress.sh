run_selfcheck() {   # run_selfcheck <suite:name>
  local key="$1"
  local tb="${key#*:}" suite="${key%%:*}"
  local dir="$SCRATCH/${suite}_${tb}" log="$SCRATCH/${suite}_${tb}/log"
  local t0; t0=$(date +%s)
  mkdir -p "$dir"
  ( cd "$REPO" && timeout -k 5 "$TIMEOUT" ${SELFCHECK_CMD[$tb]} ; \
    echo "SELFCHECK_EXIT=$?" ) > "$log" 2>&1
  local rc; rc=$(grep -oE '^SELFCHECK_EXIT=[0-9]+' "$log" | tail -1 | cut -d= -f2)
  [ -n "${rc:-}" ] || rc=1
  local rv rd
  rd="$(grep -v '^SELFCHECK_EXIT=' "$log" | grep -v '^[[:space:]]*$' | tail -1 | cut -c1-150)"
  case "$rc" in
    0)       rv=PASS ;;
    124|137) rv=TIMEOUT; rd="no result within ${TIMEOUT}s" ;;
    *)       rv=FAIL ;;
  esac
  [ -n "$rd" ] || rd="${SELFCHECK_CMD[$tb]} exited $rc without output; log: $log"
  printf '%s\t%s\t%s\t%s\n' "$key" "$rv" "$(( $(date +%s) - t0 ))" "$rd" \
      > "$SCRATCH/res.${suite}_${tb}"
}

run_one() {   # run_one <suite:name> <top-entity> <vectors-csv> <files...>
  local key="$1" top="$2" vecs="$3"; shift 3
  # The seam rows are dispatched HERE, on the name, so that the driver loop
  # below is untouched and no existing row can reach a different code path.
  case "${key#*:}" in
    seamgate_*) run_seam "$key"; return ;;
    graygate)   run_graygate "$key"; return ;;
    runguard|ipsync|descrule|cardtop|srvseam|srve2e|bdports|srvstories|c4stale|shapechk|gdnstale|shapemirror|fk33card|kvmap|seamregs|normimage|gdnconst|constimage) run_selfcheck "$key"; return ;;
  esac
  [ "$vecs" = "-" ] && vecs=""
  local tb="${key#*:}" suite="${key%%:*}"
  # The scratch directory is keyed by the SUITE-QUALIFIED name: tb/tb_rope and
  # sim/tb_rope_ps both elaborate an entity called tb_rope, and a bare-name
  # directory would have the two suites sharing a GHDL library.
  local dir="$SCRATCH/${suite}_${tb}" log="$SCRATCH/${suite}_${tb}/log"
  local run="$dir/run" work="$dir/work"
  local t0; t0=$(date +%s)
  mkdir -p "$run" "$work"
  # Both suites reach golden data as ../mem/... from the run directory.  The
  # tb/ suite uses ONLY that form; sim/ mixes it with bare vector names.
  ln -sfn "$REPO/mem" "$dir/mem"

  # Everything a testbench might open by bare name.  Committed vectors and
  # golden fixtures live in sim/; symlinking keeps them read-only in practice
  # and means nothing is ever written back into the repo.
  local f
  # `.hex` was added 2026-08-29 for sim/llama_top_w_b4_pool.hex, the committed
  # real Qwen3.5-9B weight image sim/tb_llama_top_real.vhd opens by bare name.
  # sim/llama_top_nw_b4_mean.hex, the real RMSNorm gain image
  # sim/tb_llama_top_normw.vhd opens the same way, rides on the same rule.
  # sim/llama_top_const_b4.hex, the packed GDN constants image
  # sim/tb_llama_top_bconst.vhd opens by bare name (B_CONST_IMAGE), likewise.
  # Without it that row fails with "cannot open the weight image", which reads
  # like a missing file and is a missing GLOB.
  for f in "$SIM"/*.txt "$SIM"/*.dat "$SIM"/*.csv "$SIM"/*.mem "$SIM"/*.bin \
           "$SIM"/*.hex; do
    [ -e "$f" ] && ln -sfn "$f" "$run/$(basename "$f")"
  done
  # sim/arith_vectors.txt is COMMITTED and is addressed one level up, so it is
  # symlinked beside the run directory rather than inside it.
  #
  # sim/tr.txt USED TO BE SYMLINKED HERE AND IS NOW GENERATED -- see
  # tb_trace_args and the block that calls it.  Two defects, one fix:
  #   * it is a .gitignore'd file (.gitignore's "subsystem A" stanza), so on any
  #     clean checkout the three tb_matvec_* rows died with `cannot open` and
  #     the floor below was unreachable by construction;
  #   * sim/run_matvec.sh REWRITES sim/tr.txt at whatever M/K/RI its current
  #     case asks for, so whichever shape happened to be left in the working
  #     tree is the shape the gate measured.  That is the hazard the
  #     attn_kv_quant_vec.txt row in tb_vector_args already names in as many
  #     words: a golden nothing regenerates is a golden anything can replace in
  #     silence.
  for f in "$SIM"/arith_vectors.txt; do
    [ -e "$f" ] && ln -sfn "$f" "$dir/$(basename "$f")"
  done

  # NOTE: a subshell, so that an `exit` on a build failure inside it cannot
  # skip the judging code below.  An earlier revision used a brace group and
  # six tests silently produced no result at all.
  (
    echo "### $key  (top entity: $top)"
    # --- the ../tr.txt trace, generated, never read from sim/ ----------
    local targs
    targs="$(tb_trace_args "$key")"
    if [ -n "$targs" ]; then
      if ! cc -O2 -w -I "$REPO/ref" -o "$dir/gen_tr" "$REPO/ref/matvec_int4.c" -lm 2>&1; then
        echo "VECTORGEN_BUILD_FAILED $REPO/ref/matvec_int4.c"; exit 90
      fi
      rm -f "$dir/tr.txt"
      # shellcheck disable=SC2086
      if ! "$dir/gen_tr" --trace "$dir/tr.txt" $targs >/dev/null 2>&1; then
        echo "VECTORGEN_RUN_FAILED $REPO/ref/matvec_int4.c --trace $targs"; exit 90
      fi
    fi
    # --- vectors -------------------------------------------------------
    local v stem gen args
    for v in $vecs; do
      stem="${v%.txt}"
      gen="$REPO/ref/$stem.c"
      args="$(tb_vector_args "$v")"
      if [ ! -r "$gen" ]; then
        # No generator.  If sim/ committed one, the symlink above already
        # provides it; otherwise the run will fail loudly on "cannot open".
        continue
      fi
      if [ -e "$SIM/$v" ] && [ -z "$args" ]; then
        continue          # committed, and no curated shape to re-derive
      fi
      if ! cc -O2 -w -I "$REPO/ref" -o "$dir/gen_$stem" "$gen" -lm 2>&1; then
        echo "VECTORGEN_BUILD_FAILED $gen"; exit 90
      fi
      rm -f "$run/$v"
      # shellcheck disable=SC2086
      if ! ( cd "$run" && "$dir/gen_$stem" "$v" $args ) >/dev/null 2>&1; then
        echo "VECTORGEN_RUN_FAILED $gen"; exit 90
      fi
    done

    # --- analysis ------------------------------------------------------
    for f in "$@"; do
      if ! "$GHDL" -a $STD $RELAX --workdir="$work" "$REPO/$f" 2>&1; then
        echo "ANALYSIS_FAILED $f"; exit 91
      fi
    done

    # --- run.  mcode: -e emits nothing, so -r is called directly. -------
    # shellcheck disable=SC2046,SC2086
    ( cd "$run" && timeout -k 5 "$TIMEOUT" \
        "$GHDL" -r $STD $RELAX --workdir="$work" "$top" \
        $(tb_args "$key") --max-stack-alloc=0 2>&1 )
    echo "GHDL_EXIT=$?"
  ) > "$log" 2>&1

  # ---- judge --------------------------------------------------------
  local rc body marker nocheck
  rc=$(grep -oE '^GHDL_EXIT=[0-9]+' "$log" | tail -1 | cut -d= -f2)
  body=$(grep -avE '^(### |GHDL_EXIT=)' "$log")

  # Elapsed seconds are part of the result, not decoration: --quick's exclusion
  # list is only honest if it was chosen from measurement, and the slow test in
  # a 20 minute run is the first thing anyone wants to know.
  verdict() {
    printf '%s\t%s\t%s\t%s\n' "$key" "$1" "$(( $(date +%s) - t0 ))" "$2" \
      > "$SCRATCH/res.${suite}_${tb}"
  }

  if grep -q '^VECTORGEN' "$log"; then
    verdict ERROR "reference vector generator failed: $(grep -m1 '^VECTORGEN' "$log")"; return
  fi
  if grep -q '^ANALYSIS_FAILED' "$log"; then
    verdict ERROR "ghdl -a failed on $(grep -m1 '^ANALYSIS_FAILED' "$log" | cut -d' ' -f2): $(printf '%s' "$body" | grep -aiE 'error' | head -1 | cut -c1-120)"; return
  fi
  [ -n "${rc:-}" ] || rc=1
  if [ "$rc" = "124" ] || [ "$rc" = "137" ]; then
    verdict TIMEOUT "no result within ${TIMEOUT}s -- unguarded clock or deadlock, NOT the same thing as a failure"; return
  fi
  if [ -z "$(printf '%s' "$body" | tr -d '[:space:]')" ]; then
    verdict FAIL "produced NO output at all (exit $rc)"; return
  fi
  local noise; noise="$(tb_expected_noise "$key")"
  if [ -n "$noise" ]; then
    body="$(printf '%s' "$body" | grep -avE "$noise")"
  fi

  # A line that REPORTS A FAILURE COUNT OF ZERO is not a failure.  tb/
  # tb_divider_rs ends a clean run with "DIVIDER TB RESULT: PASS=608 FAIL=0",
  # and a bare \bFAIL\b match calls that a failed test -- which is exactly the
  # inverse of the mistake clause 6 guards against, and just as wrong.  Only
  # ZERO-valued counters are neutralised: "FAIL=3" still matches, and the
  # neutralisation is applied to the FAILURE scan only, never to the success
  # scan, so it cannot manufacture a pass.
  local scan
  scan="$(printf '%s' "$body" | sed -E 's/\b(FAIL|FAILURE|FAILURES|MISMATCH|MISMATCHES|ERROR|ERRORS)[[:space:]]*[=:][[:space:]]*0+\b//g')"
  if [ "$rc" != "0" ]; then
    verdict FAIL "exit $rc: $(printf '%s' "$scan" | grep -aE "$FAIL_RE" | head -1 | cut -c1-160)"; return
  fi
  # `grep -c`, NEVER `grep -q`, ON A printf PIPELINE UNDER pipefail.  `-q`
  # exits at the FIRST match and closes the pipe; if printf has not finished
  # writing, printf dies of SIGPIPE, `set -o pipefail` makes the pipeline's
  # status printf's, and the `if` reads a MATCH as NO MATCH.  Invisible on a
  # small log (printf is done before grep exits) and reliable on a large
  # one.  MEASURED 2026-09-18 on sim:tb_fk33_seam_wdog against a seam that
  # FAILS it: a 13 MB log with six `(report error)` lines at line ~7,000 of
  # 97,000 was judged NOVERDICT three runs out of three, while an
  # instrumented `grep -c` in the same function counted 6.  NOVERDICT is
  # still not green, so the gate stayed red -- but a PASSING row whose
  # marker sits early in a large log would be misjudged the same way, and
  # that one costs a re-run rather than a wrong pass.  `-c` reads all input.
  if [ "$(printf '%s' "$scan" | grep -acE "$FAIL_RE")" -gt 0 ]; then
    verdict FAIL "$(printf '%s' "$scan" | grep -aE "$FAIL_RE" | head -1 | cut -c1-160)"; return
  fi

  marker="$(tb_pass_marker "$key")"
  if [ -n "$marker" ]; then
    if [ "$(printf '%s' "$body" | grep -acE "$marker")" -gt 0 ]; then
      verdict PASS "$(printf '%s' "$body" | grep -aE "$marker" | head -1 | cut -c1-140)"; return
    fi
    verdict NOVERDICT "ran clean but its declared success marker ('$marker') never appeared"; return
  fi

  nocheck="$(tb_nocheck_reason "$key")"
  if [ -n "$nocheck" ]; then
    verdict NOCHECK "$nocheck"; return
  fi

  if [ "$(printf '%s' "$body" | grep -aciE "$PASS_RE")" -gt 0 ]; then
    verdict PASS "$(printf '%s' "$body" | grep -aiE "$PASS_RE" | head -1 | cut -c1-140)"; return
  fi
  verdict NOVERDICT "exit 0 and no failure marker, but NO success marker either -- that is not evidence of a pass"
}

# ===========================================================================
# 4. DRIVE
# ===========================================================================
# ---- rows and inputs that exist only in THIS working tree -----------------
# See section 1b.  Printed unconditionally when git can see this tree, with an
# explicit "(none)", because a section that appears only on bad news is a
# section nobody learns to read.  Called from BOTH the --list path and the full
# summary: --list runs no simulation, so it answers "is my gate reproducible?"
# in about two seconds, which is the version of this check anyone will actually
# run before committing.
report_not_in_git() {
  [ "$GIT_VISIBLE" = 1 ] || return 0
  echo
  echo "-- NOT IN GIT (these rows/inputs are yours alone) ------------------------------"
  if [ -z "$UNTRACKED_ROWS$IGNORED_ROWS$UNTRACKED_DEPS$IGNORED_DEPS" ]; then
    echo "(none) -- every planned row and every file it compiles is tracked."
    return 0
  fi
  local k
  for k in $UNTRACKED_ROWS; do
    printf 'UNTRACKED  row    %-34s not in git: a gate row for you, absent for a clone\n' "$k"
  done
  for k in $IGNORED_ROWS; do
    printf 'IGNORED    row    %-34s .gitignore hides it -- git status will NEVER mention it\n' "$k"
  done
  for k in $UNTRACKED_DEPS; do
    printf 'UNTRACKED  source %-34s compiled by some row; absent, that row goes SKIPPED\n' "$k"
  done
  for k in $IGNORED_DEPS; do
    printf 'IGNORED    source %-34s .gitignore hides it -- git status will NEVER mention it\n' "$k"
  done
  echo
  echo "   The pass count is NOT reproducible from a clean checkout while this"
  echo "   list is non-empty.  Commit them, delete them, or leave them -- but do"
  echo "   NOT raise BASELINE_PASS from a run that included them."
  return 0
}

selected=()
skipped_names=(); skipped_reasons=()
OPTIONAL_ROWS=""   # rows that ran only because an external prerequisite is here
while IFS=$'\t' read -r name suite status reason flist top vecs; do
  key="$suite:$name"
  [[ " $SUITES " == *" $suite "* ]] || continue
  [ -n "$ONLY" ] && [[ "$name" != *"$ONLY"* ]] && continue
  if [ "$status" = "SKIP" ]; then
    skipped_names+=("$key"); skipped_reasons+=("$reason"); continue
  fi
  if [ "$QUICK" = 1 ] && [[ "$SLOW_SET" == *" $key "* ]]; then
    skipped_names+=("$key")
    skipped_reasons+=("--quick: slow seam/top-level test, deliberately excluded -- run without --quick")
    continue
  fi
  # An absent EXTERNAL prerequisite is a SKIP with its path, never a failure.
  # See tb_prereq.  Counted as an optional row so the baseline note can say why
  # a run is above the floor instead of inviting a raise.
  preq="$(tb_prereq "$key")"
  if [ -n "$preq" ] && [ ! -r "$preq" ]; then
    skipped_names+=("$key")
    skipped_reasons+=("external prerequisite not in this tree and not in git: $preq -- one of the .mv4i files tools/pack_int4.py writes from the GGUF model set. Override with MV4I_FK33_FILE")
    continue
  fi
  [ -n "$preq" ] && OPTIONAL_ROWS="$OPTIONAL_ROWS $key"
  # Keep the '-' placeholder: with IFS=tab an EMPTY field collapses and every
  # field after it shifts, which is how the analysis file list once ended up in
  # the vectors slot and every test reported "cannot find entity".
  selected+=("$key"$'\t'"$top"$'\t'"$vecs"$'\t'"$flist")
done < "$PLAN"

if [ "$LIST_ONLY" = 1 ]; then
